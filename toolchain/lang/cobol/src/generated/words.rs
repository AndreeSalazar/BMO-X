/// Es `w` (en MAYUSCULAS) una palabra reservada de COBOL?
pub fn is_reserved(w: &str) -> bool {
    RESERVED.binary_search(&w).is_ok()
}

/// Etiqueta de `w`: era estandar (COBOL74..2023), "STANDARD", o
/// "VENDOR:<cat>". None si no es reservada.
pub fn reserved_since(w: &str) -> Option<&'static str> {
    RESERVED_STD.binary_search_by(|(k, _)| k.cmp(&w))
        .ok().map(|i| RESERVED_STD[i].1)
}

/// Es `w` ESENCIA COBOL estandar (no extension de vendor)?
pub fn is_essence(w: &str) -> bool {
    reserved_since(w).map_or(false, |s| !s.starts_with("VENDOR:"))
}

/// Es `w` una extension de VENDOR (IBM/VAX/pantalla, NO estandar)?
pub fn is_vendor(w: &str) -> bool {
    reserved_since(w).map_or(false, |s| s.starts_with("VENDOR:"))
}

/// Verbo COBOL -> nombre de la variante CobolStatement que lo emite.
/// `None` = reconocido pero aun sin codegen.
pub fn verb_kind(w: &str) -> Option<&'static str> {
    match w {
        "ACCEPT" => Some("Accept"),
        "ADD" => Some("Add"),
        "CLOSE" => Some("Close"),
        "COMPUTE" => Some("Compute"),
        "DISPLAY" => Some("Display"),
        "DIVIDE" => Some("Divide"),
        "IF" => Some("If"),
        "MOVE" => Some("Move"),
        "MULTIPLY" => Some("Multiply"),
        "OPEN" => Some("Open"),
        "PERFORM" => Some("Perform"),
        "READ" => Some("Read"),
        "STOP" => Some("StopRun"),
        "SUBTRACT" => Some("Subtract"),
        "WRITE" => Some("Write"),
        _ => None,
    }
}

