/// Es `w` (en MAYUSCULAS) una palabra reservada de COBOL?
pub fn is_reserved(w: &str) -> bool {
    RESERVED.binary_search(&w).is_ok()
}

/// Estandar donde `w` entro como reservada (None si no lo es).
pub fn reserved_since(w: &str) -> Option<&'static str> {
    RESERVED_STD.binary_search_by(|(k, _)| k.cmp(&w))
        .ok().map(|i| RESERVED_STD[i].1)
}

/// Verbo COBOL -> nombre de la variante CobolStatement que lo emite.
/// `None` = reconocido pero aun sin codegen.
