// Bump allocator state (must be before global_allocator)
static mut ALLOC_START: u64 = 0;
static mut ALLOC_END: u64 = 0;
static mut ALLOC_CURSOR: u64 = 0;

// ── Global allocator ─────────────────────────────────────────
// (defined after BumpAllocator below, but #[global_allocator] must be at module level)

#[global_allocator]
static KERNEL_ALLOCATOR: KernelAllocator = KernelAllocator;
struct KernelAllocator;
unsafe impl core::alloc::GlobalAlloc for KernelAllocator {
    unsafe fn alloc(&self, layout: core::alloc::Layout) -> *mut u8 {
        let align = layout.align() as u64;
        let size = layout.size() as u64;
        let mut c = ALLOC_CURSOR;
        c = (c + align - 1) & !(align - 1);
        if c + size > ALLOC_END { return core::ptr::null_mut(); }
        ALLOC_CURSOR = c + size;
        c as *mut u8
    }
    unsafe fn dealloc(&self, _ptr: *mut u8, _layout: core::alloc::Layout) {}
}

unsafe fn init_heap(base: u64, size: u64) {
    ALLOC_START = base; ALLOC_END = base + size; ALLOC_CURSOR = base;
}

// ── Port I/O ────────────────────────────────────────────────

unsafe fn inb(port: u16) -> u8 {
    let mut v: u8; asm!("in al, dx", out("al") v, in("dx") port); v
}
unsafe fn outb(port: u16, val: u8) { asm!("out dx, al", in("dx") port, in("al") val); }
unsafe fn inw(port: u16) -> u16 {
    let mut v: u16; asm!("in ax, dx", out("ax") v, in("dx") port); v
}

// ═══════════════════════════════════════════════════════════════
//  Serial
// ═══════════════════════════════════════════════════════════════

fn serial_write(s: &str) {
    for &b in s.as_bytes() {
        unsafe {
            while inb(0x3F8 + 5) & 0x20 == 0 {}
            outb(0x3F8, b);
        }
    }
}

fn serial_write_u64(mut v: u64, min_width: usize) {
    if v == 0 {
        for _ in 0..min_width.min(1) { unsafe { outb(0x3F8, b'0'); } }
        return;
    }
    let mut buf = [0u8; 16]; let mut i = 0;
    while v > 0 { let d = (v & 0xF) as u8; buf[i] = if d < 10 { b'0' + d } else { b'a' + d - 10 }; v >>= 4; i += 1; }
    while i < min_width && i < 16 { buf[i] = b'0'; i += 1; }
    while i > 0 { i -= 1; unsafe { outb(0x3F8, buf[i]); } }
}

