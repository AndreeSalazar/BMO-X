// ═══════════════════════════════════════════════════════════════
//  Scheduler (simple round-robin)
// ═══════════════════════════════════════════════════════════════

const MAX_TASKS: usize = 16;

#[derive(Clone, Copy)]
struct Task {
    rsp: u64,
    stack_top: u64,
    rip: u64,
    rflags: u64,
    active: bool,
}

static mut TASKS: [Task; MAX_TASKS] = [Task { rsp: 0, stack_top: 0, rip: 0, rflags: 0, active: false }; MAX_TASKS];
static mut CURRENT_TASK: usize = 0;
static mut TASK_COUNT: usize = 0;
static mut SCHED_LOCK: u64 = 0;

fn task_alloc(flags: u32, _cpu: u32) -> *mut u8 {
    unsafe {
        for i in 0..MAX_TASKS {
            if !TASKS[i].active {
                TASKS[i] = Task { rsp: 0, stack_top: 0, rip: 0, rflags: flags as u64, active: true };
                TASK_COUNT += 1;
                return core::ptr::addr_of_mut!(TASKS[i]) as *mut u8;
            }
        }
    }
    core::ptr::null_mut()
}

fn task_current() -> *mut u8 {
    unsafe { core::ptr::addr_of_mut!(TASKS[CURRENT_TASK]) as *mut u8 }
}

fn task_current_index() -> usize { unsafe { CURRENT_TASK } }

fn task_set_current(idx: usize) { unsafe { CURRENT_TASK = idx.min(MAX_TASKS - 1); } }

fn task_get(idx: usize) -> *mut u8 {
    if idx >= MAX_TASKS { return core::ptr::null_mut(); }
    unsafe { core::ptr::addr_of_mut!(TASKS[idx]) as *mut u8 }
}

fn task_free(t: *mut u8) {
    unsafe {
        let idx = ((t as usize) - (core::ptr::addr_of!(TASKS) as usize)) / core::mem::size_of::<Task>();
        if idx < MAX_TASKS { TASKS[idx].active = false; TASK_COUNT = TASK_COUNT.saturating_sub(1); }
    }
}

fn task_pick_next() -> usize {
    unsafe {
        let start = CURRENT_TASK;
        for i in 1..=MAX_TASKS {
            let idx = (start + i) % MAX_TASKS;
            if TASKS[idx].active { return idx; }
        }
    }
    0
}

fn task_block_on(_event: u64) {
    unsafe { CURRENT_TASK = task_pick_next(); }
}

fn task_wake_on(_event: u64, _idx: usize) -> usize { 0 }

fn schedule() {
    unsafe {
        let next = task_pick_next();
        if next != CURRENT_TASK && TASKS[next].active {
            CURRENT_TASK = next;
        }
    }
}

fn yield_now() { schedule(); }

