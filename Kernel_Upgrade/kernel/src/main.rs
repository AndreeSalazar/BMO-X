fn get_glyph(ch: u8) -> &'static [u8; 16] {
    if ch < 32 || ch > 126 {
        const FB: [u8;16] = [0xAA,0x55,0xAA,0x55,0xAA,0x55,0xAA,0x55,0xAA,0x55,0xAA,0x55,0xAA,0x55,0xAA,0x55];
        &FB
    } else { &FONT[(ch - 32) as usize] }
}

unsafe fn put_pixel(x: u32, y: u32, color: u32) {
    if x >= FB_WIDTH || y >= FB_HEIGHT { return; }
    let idx = (y * FB_STRIDE + x) as usize;
    let ptr = (FB_BASE + (idx * 4) as u64) as *mut u32;
    ptr.write_volatile(color);
}

unsafe fn draw_char(col: u32, row: u32, ch: u8, fg: u32) {
    let g = get_glyph(ch); let bx = col * 8; let by = row * 16;
    for gy in 0..16 {
        let bits = g[gy as usize];
        for gx in 0..8 { if bits & (1 << (7 - gx)) != 0 { put_pixel(bx + gx, by + gy, fg); } }
    }
}

unsafe fn clear_screen() {
    for y in 0..FB_HEIGHT { for x in 0..FB_WIDTH { put_pixel(x, y, 0); } }
}

unsafe fn fill_rect(x: u32, y: u32, w: u32, h: u32, color: u32) {
    for dy in y..(y + h).min(FB_HEIGHT) {
        for dx in x..(x + w).min(FB_WIDTH) { put_pixel(dx, dy, color); }
    }
}

