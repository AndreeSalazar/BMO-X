fn rdtsc() -> u64 {
    let lo: u32; let hi: u32;
    unsafe { asm!("rdtsc", out("eax") lo, out("edx") hi); }
    ((hi as u64) << 32) | lo as u64
}

fn tsc_per_sec() -> u64 {
    // Will be overwritten by BootContext.tsc_freq
    3_700_000_000
}

fn tsc_busy_wait_ms(tsc_freq: u64, ms: u64) {
    let start = rdtsc();
    let target = start + (tsc_freq / 1000) * ms;
    while rdtsc() < target { unsafe { asm!("pause"); } }
}

fn halt() { unsafe { asm!("hlt"); } }

