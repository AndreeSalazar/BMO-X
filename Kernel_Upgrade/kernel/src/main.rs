const NR_DEBUG_PRINT: u64 = 0xF0;
const NR_PROC_EXIT: u64 = 0x3A;
const NR_KEYBOARD_POLL: u64 = 0x38;
const NR_FB_INFO: u64 = 0x60;
const NR_YIELD: u64 = 0x03;
const NR_CLOCK: u64 = 0x50;

#[no_mangle]
pub extern "C" fn syscall_handler(nr: u64, a0: u64, a1: u64, _a2: u64, _a3: u64, _a4: u64, _a5: u64) -> u64 {
    match nr {
        NR_DEBUG_PRINT => {
            let ptr = a0 as *const u8; let len = a1 as usize;
            for i in 0..len { unsafe { while inb(0x3F8 + 5) & 0x20 == 0 {} outb(0x3F8, *ptr.add(i)); } }
            0
        }
        NR_PROC_EXIT => { serial_write("[kernel] process exit\n"); loop { unsafe { asm!("hlt"); } } }
        NR_KEYBOARD_POLL => {
            unsafe {
                let s = inb(0x64);
                if s & 1 != 0 { inb(0x60) as u64 } else { 0 }
            }
        }
        NR_FB_INFO => unsafe { (FB_BASE & 0xFFFF_FFFF) as u64 | ((FB_WIDTH as u64) << 32) | ((FB_HEIGHT as u64) << 48) }
        NR_YIELD => { yield_now(); 0 }
        NR_CLOCK => rdtsc(),
        0x100..=0x1FF => crate::ring3::gateway::dispatch(nr as u16, a0, a1, _a2, _a3, _a4, _a5),
        _ => 0,
    }
}

// ═══════════════════════════════════════════════════════════════
//  Entry Point
// ═══════════════════════════════════════════════════════════════

static mut BOOT_INFO: BootInfo = BootInfo {
    magic: 0, version: 0, _pad: 0,
    fb_addr: 0, fb_size: 0, fb_width: 0, fb_height: 0, fb_stride: 0,
    fb_pixel_format: PixelFormat::Unknown,
    memory_map_count: 0, _pad2: 0,
    memory_map: [MemoryEntryOld { base: 0, size: 0, mem_type: MemoryType::Reserved, _pad: 0 }; MAX_MEMORY_ENTRIES_OLD],
    rsdp_addr: 0,
    kernel_base: 0, kernel_size: 0, services_base: 0, services_size: 0, services_entry: 0,
    stack_top: 0, stack_size: 0, reserved_addr: 0, reserved_size: 0,
    uefi_system_table: 0, module_count: 0, _pad3: 0,
    modules: [boot_info::ModuleEntry { base: 0, size: 0, entry_point: 0 }; boot_info::MAX_MODULES],
    xhci_mmio: 0, xhci_mmio2: 0,
};

#[no_mangle]
pub extern "C" fn _start(ctx_ptr: *mut BootContext) -> ! {
    let ctx = unsafe { &*ctx_ptr };

    serial_write("\n[kernel] ══════════════════════════════════════\n");
    serial_write("[kernel]  BMO Kernel v2 — Faggin Runtime\n");
    serial_write("[kernel] ══════════════════════════════════════\n");

    // ── 1. Init framebuffer ──────────────────────────────
    unsafe {
        FB_BASE = ctx.fb_addr; FB_WIDTH = ctx.fb_width;
        FB_HEIGHT = ctx.fb_height; FB_STRIDE = ctx.fb_stride;
    }

    // ── 2. Init heap ──────────────────────────────────────
    unsafe {
        // Use a region after the kernel (0x400000 + some offset) for bump heap
        init_heap(0x500000, 0x100000); // 1MB heap
    }

    // ── 3. Build HalServices ──────────────────────────────
    let hal = build_hal(ctx);
    serial_write("[kernel] HalServices built\n");

    // ── 4. Build BootInfo from BootContext for Ring 3 modules ─
    unsafe {
        BOOT_INFO.magic = boot_info::BOOT_MAGIC;
        BOOT_INFO.version = boot_info::PROTOCOL_VERSION;
        BOOT_INFO.fb_addr = ctx.fb_addr; BOOT_INFO.fb_width = ctx.fb_width;
        BOOT_INFO.fb_height = ctx.fb_height; BOOT_INFO.fb_stride = ctx.fb_stride;
        BOOT_INFO.rsdp_addr = ctx.rsdp;
        for i in 0..ctx.memory_map_count as usize {
            if (i as usize) < MAX_MEMORY_ENTRIES_OLD {
                BOOT_INFO.memory_map[i] = MemoryEntryOld {
                    base: ctx.memory_map[i].base, size: ctx.memory_map[i].size,
                    mem_type: MemoryType::Usable, _pad: 0,
                };
                BOOT_INFO.memory_map_count = i as u32 + 1;
            }
        }
    }

    // ── 5. Display boot screen ────────────────────────────
    unsafe {
        if FB_BASE != 0 && FB_WIDTH > 0 {
            clear_screen();
            draw_char(1, 0, b'=', 0xFF00FF00);
            hal_print_at(3, 0, 0xFF00FF00, "BMO Kernel v2 — Faggin Runtime");
            hal_print_at(1, 2, 0xFF008800, "Stage 1: Arch .......... OK");
            hal_print_at(1, 3, 0xFF008800, "Stage 2: Memory ........ OK");
            hal_print_at(1, 4, 0xFF008800, "Stage 3: Devices ....... OK");
            hal_print_at(1, 5, 0xFF008800, "Kernel: Runtime ........ OK");
            hal_print_at(1, 7, 0xFFFFB000, "Loading Ring 3 modules...");
        }
    }

    // ── 6. Try to load bmo_core module ────────────────────
    serial_write("[kernel] Loading Ring 3 modules...\n");

    // Search BootContext for modules (from stage_base entries beyond kernel)
    let mut found_module = false;
    for i in 0..boot_context::MAX_STAGES {
        let base = ctx.stage_base[i];
        let size = ctx.stage_size[i];
        let entry = ctx.stage_entry[i];

        // Skip stages 0-3 (stage1..kernel)
        if i <= 3 { continue; }
        if base == 0 || entry == 0 { continue; }

        serial_write("[kernel]   Module "); serial_write_u64(i as u64, 10);
        serial_write(": base=0x"); serial_write_u64(base, 16);
        serial_write(" entry=0x"); serial_write_u64(entry, 16);
        serial_write(" size="); serial_write_u64(size, 10); serial_write("\n");

        unsafe {
            BOOT_INFO.modules[BOOT_INFO.module_count as usize] = ModuleEntry {
                base, size, entry_point: entry,
            };
            BOOT_INFO.module_count += 1;
        }
    }

    if unsafe { BOOT_INFO.module_count > 0 } {
        found_module = true;
        serial_write("[kernel] Jumping to Ring 3 module\n");
        unsafe {
            hal_print_at(1, 8, 0xFF00FF00, "Module found! Jumping to Ring 3...");
        }

        let module_entry = unsafe { BOOT_INFO.modules[0].entry_point };
        if module_entry != 0 {
            // Call the module's entry function (it runs in Ring 0 initially)
            // It will call ring3_transition when ready
            let entry_fn: extern "C" fn(*const HalServices) -> ! =
                unsafe { core::mem::transmute(module_entry) };
            entry_fn(&hal as *const _);
        }
    }

    // ── 7. Fallback main loop ─────────────────────────────
    if !found_module {
        unsafe {
            hal_print_at(1, 8, 0xFFFF0000, "No Ring 3 modules loaded");
            hal_print_at(1, 9, 0xFF008800, "Running in fallback mode");
        }
        serial_write("[kernel] No modules found, entering fallback loop\n");
    }

    let mut tick = 0u64;
    let tsc_hz = tsc_per_sec();
    loop {
        tick += 1;
        // Blink cursor every ~500ms
        if tick % 100_000_000 == 0 { unsafe {
            let c = if (tick / 100_000_000) % 2 == 0 { b'_' } else { b' ' };
            draw_char(1, 10, c, 0xFF00FF00);
        }}
        // Periodic serial heartbeat
        if tick % 50_000_000 == 0 {
            serial_write("[kernel]  heartbeat ");
            serial_write_u64(tick / 50_000_000, 10);
            serial_write("\n");
        }
        // Poll keyboard
        unsafe {
            let status = inb(0x64);
            if status & 1 != 0 {
                let scancode = inb(0x60);
                serial_write("[kernel] scancode=0x");
                serial_write_u64(scancode as u64, 2);
                serial_write("\n");
            }
        }
        if tick % 1_000_000 == 0 { unsafe { asm!("hlt"); } }
    }
}

#[panic_handler]
fn panic(info: &PanicInfo) -> ! {
    serial_write("\n[PANIC] ");
    if let Some(s) = info.message().as_str() { serial_write(s); }
    serial_write("\n");
    loop { unsafe { asm!("hlt"); } }
}
