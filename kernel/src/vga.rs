// Minimal CP437-compatible font covering ASCII 32..126.
// Each glyph is 16 bytes (one byte per row, MSB = leftmost pixel).

pub fn get_glyph(ch: u8) -> [u8; 16] {
    if ch < 32 || ch > 126 {
        return FONT_FALLBACK;
    }
    FONT_DATA[(ch - 32) as usize]
}

