//! Display driver — VGA text mode (80x25) OR framebuffer (1920x1080x32bpp).
//!
//! Automatically selects mode based on BootInfo.vbe_mode:
//!   0 = VGA text mode (0xB8000, 80x25, 16 colors)
//!   1 = VBE framebuffer (1920x1080, 32bpp, pixel rendering)

const VGA_BUFFER: usize = 0xB8000;
const VGA_WIDTH: usize = 80;
const VGA_HEIGHT: usize = 25;

// Framebuffer constants for 1920x1080
const FB_WIDTH: usize = 1920;
const FB_HEIGHT: usize = 1080;

// Built-in 8x16 font (PSF-style bitmap font for ASCII 32..127)
// Each character is 8 pixels wide, 16 pixels tall = 16 bytes per glyph.
const FONT_WIDTH: usize = 8;
const FONT_HEIGHT: usize = 16;
const FONT_COLS: usize = FB_WIDTH / FONT_WIDTH;   // 240
const FONT_ROWS: usize = FB_HEIGHT / FONT_HEIGHT;  // 67

#[allow(dead_code)]
#[derive(Debug, Clone, Copy)]
#[repr(u8)]
pub enum Color {
    Black = 0, Blue = 1, Green = 2, Cyan = 3,
    Red = 4, Magenta = 5, Brown = 6, LightGray = 7,
    DarkGray = 8, LightBlue = 9, LightGreen = 10, LightCyan = 11,
    LightRed = 12, Pink = 13, Yellow = 14, White = 15,
}

impl Color {
    /// Convert VGA color to 32-bit ARGB for framebuffer.
    fn to_argb(self) -> u32 {
        match self {
            Color::Black     => 0xFF0A0A0E,  // Dark background
            Color::Blue      => 0xFF1A3A5C,
            Color::Green     => 0xFF00AA00,
            Color::Cyan      => 0xFF00AAAA,
            Color::Red       => 0xFFFF4444,
            Color::Magenta   => 0xFFAA00AA,
            Color::Brown     => 0xFFAA5500,
            Color::LightGray => 0xFFAAAAAA,
            Color::DarkGray  => 0xFF555555,
            Color::LightBlue => 0xFF5599FF,
            Color::LightGreen => 0xFF55FF55,
            Color::LightCyan  => 0xFF55FFFF,
            Color::LightRed   => 0xFFFF5555,
            Color::Pink       => 0xFFFF55FF,
            Color::Yellow     => 0xFFFFFF55,
            Color::White      => 0xFFE0E0E0,
        }
    }
}

/// Display writer supporting both VGA text and framebuffer pixel modes.
pub struct VgaWriter {
    pub col: usize,
    pub row: usize,
    color: u8,
    // Framebuffer mode
    fb_addr: usize,
    fb_pitch: usize,
    fb_mode: bool,  // true = 1920x1080 framebuffer, false = VGA text
}

impl VgaWriter {
    pub fn new() -> Self {
        Self {
            col: 0,
            row: 0,
            color: 0x07,
            fb_addr: VGA_BUFFER,
            fb_pitch: 160,
            fb_mode: false,
        }
    }

    /// Create from BootInfo fields.
    pub fn from_boot_info(fb_addr: u64, fb_pitch: u64, vbe_mode: u64) -> Self {
        Self {
            col: 0,
            row: 0,
            color: 0x07,
            fb_addr: fb_addr as usize,
            fb_pitch: fb_pitch as usize,
            fb_mode: vbe_mode == 1,
        }
    }

    pub fn is_graphics_mode(&self) -> bool {
        self.fb_mode
    }

    pub fn clear(&mut self) {
        if self.fb_mode {
            // Clear framebuffer to dark background
            let bg = Color::Black.to_argb();
            let pixels = FB_WIDTH * FB_HEIGHT;
            let buf = self.fb_addr as *mut u32;
            for i in 0..pixels {
                unsafe { buf.add(i).write_volatile(bg); }
            }
        } else {
            let buf = VGA_BUFFER as *mut u16;
            for i in 0..(VGA_WIDTH * VGA_HEIGHT) {
                unsafe { buf.add(i).write_volatile(0x0720); }
            }
        }
        self.col = 0;
        self.row = 0;
    }

    pub fn write_byte(&mut self, byte: u8) {
        if byte == b'\n' { self.newline(); return; }

        if self.fb_mode {
            self.fb_write_byte(byte);
        } else {
            self.vga_write_byte(byte);
        }
    }

    // ── VGA text mode ────────────────────────────────────────────────────

    fn vga_write_byte(&mut self, byte: u8) {
        if self.row >= VGA_HEIGHT { self.scroll(); }
        let off = self.row * VGA_WIDTH + self.col;
        let buf = VGA_BUFFER as *mut u16;
        unsafe { buf.add(off).write_volatile((self.color as u16) << 8 | byte as u16); }
        self.col += 1;
        let max_col = if self.fb_mode { FONT_COLS } else { VGA_WIDTH };
        if self.col >= max_col { self.newline(); }
    }

    // ── Framebuffer pixel mode ───────────────────────────────────────────

    fn fb_write_byte(&mut self, byte: u8) {
        let max_rows = FONT_ROWS;
        if self.row >= max_rows { self.scroll(); }

        // Get the glyph bitmap
        let glyph = get_glyph(byte);
        let fg = Color::from_vga_attr(self.color & 0x0F).to_argb();
        let bg = Color::Black.to_argb();

        let base_x = self.col * FONT_WIDTH;
        let base_y = self.row * FONT_HEIGHT;

        let buf = self.fb_addr as *mut u32;
        let pitch_px = self.fb_pitch / 4; // pitch in pixels (4 bytes per pixel)

        for gy in 0..FONT_HEIGHT {
            let row_bits = glyph[gy];
            for gx in 0..FONT_WIDTH {
                let px = if row_bits & (0x80 >> gx) != 0 { fg } else { bg };
                let off = (base_y + gy) * pitch_px + (base_x + gx);
                unsafe { buf.add(off).write_volatile(px); }
            }
        }

        self.col += 1;
        if self.col >= FONT_COLS { self.newline(); }
    }

    // ── Common methods ───────────────────────────────────────────────────

    pub fn write_str(&mut self, s: &str) {
        for b in s.bytes() { self.write_byte(b); }
    }

    pub fn write_str_color(&mut self, s: &str, fg: Color) {
        let old = self.color;
        self.color = fg as u8;
        self.write_str(s);
        self.color = old;
    }

    pub fn newline(&mut self) {
        self.col = 0;
        self.row += 1;
        let max_rows = if self.fb_mode { FONT_ROWS } else { VGA_HEIGHT };
        if self.row >= max_rows { self.scroll(); }
    }

    fn scroll(&mut self) {
        if self.fb_mode {
            self.fb_scroll();
        } else {
            self.vga_scroll();
        }
    }

    fn vga_scroll(&mut self) {
        let buf = VGA_BUFFER as *mut u16;
        for r in 1..VGA_HEIGHT {
            for c in 0..VGA_WIDTH {
                unsafe {
                    let v = buf.add(r * VGA_WIDTH + c).read_volatile();
                    buf.add((r - 1) * VGA_WIDTH + c).write_volatile(v);
                }
            }
        }
        for c in 0..VGA_WIDTH {
            unsafe { buf.add((VGA_HEIGHT - 1) * VGA_WIDTH + c).write_volatile(0x0720); }
        }
        self.row = VGA_HEIGHT - 1;
    }

    fn fb_scroll(&mut self) {
        let buf = self.fb_addr as *mut u32;
        let pitch_px = self.fb_pitch / 4;
        let row_pixels = FONT_HEIGHT * pitch_px;
        let bg = Color::Black.to_argb();

        // Copy rows up by one character height
        let total_rows = (FONT_ROWS - 1) * FONT_HEIGHT;
        for py in 0..total_rows {
            for px in 0..FB_WIDTH {
                unsafe {
                    let src = buf.add((py + FONT_HEIGHT) * pitch_px + px).read_volatile();
                    buf.add(py * pitch_px + px).write_volatile(src);
                }
            }
        }

        // Clear bottom row
        let last_start = total_rows;
        for py in 0..FONT_HEIGHT {
            for px in 0..FB_WIDTH {
                unsafe {
                    buf.add((last_start + py) * pitch_px + px).write_volatile(bg);
                }
            }
        }

        self.row = FONT_ROWS - 1;
    }

    pub fn write_u64(&mut self, mut val: u64) {
        if val == 0 { self.write_byte(b'0'); return; }
        let mut buf = [0u8; 20];
        let mut i = 0;
        while val > 0 { buf[i] = b'0' + (val % 10) as u8; val /= 10; i += 1; }
        while i > 0 { i -= 1; self.write_byte(buf[i]); }
    }

    pub fn write_hex16(&mut self, val: u16) {
        const HEX: &[u8] = b"0123456789ABCDEF";
        for &shift in &[12u16, 8, 4, 0] {
            self.write_byte(HEX[((val >> shift) & 0xF) as usize]);
        }
    }

    pub fn write_hex32(&mut self, val: u32) {
        const HEX: &[u8] = b"0123456789ABCDEF";
        for &shift in &[28u32, 24, 20, 16, 12, 8, 4, 0] {
            self.write_byte(HEX[((val >> shift) & 0xF) as usize]);
        }
    }

    /// Draw a horizontal separator line.
    pub fn write_separator(&mut self) {
        if self.fb_mode {
            // Draw a gradient line across the framebuffer
            let y = self.row * FONT_HEIGHT;
            let buf = self.fb_addr as *mut u32;
            let pitch_px = self.fb_pitch / 4;
            for px in 0..FB_WIDTH {
                let intensity = (px * 255 / FB_WIDTH) as u32;
                let color = 0xFF000000 | (intensity << 16) | (intensity / 2) << 8 | 0x40;
                unsafe { buf.add(y * pitch_px + px).write_volatile(color); }
            }
            self.newline();
        } else {
            for _ in 0..VGA_WIDTH {
                self.write_byte(b'=');
            }
        }
    }
}

impl Color {
    fn from_vga_attr(attr: u8) -> Self {
        match attr & 0x0F {
            0 => Color::Black,
            1 => Color::Blue,
            2 => Color::Green,
            3 => Color::Cyan,
            4 => Color::Red,
            5 => Color::Magenta,
            6 => Color::Brown,
            7 => Color::LightGray,
            8 => Color::DarkGray,
            9 => Color::LightBlue,
            10 => Color::LightGreen,
            11 => Color::LightCyan,
            12 => Color::LightRed,
            13 => Color::Pink,
            14 => Color::Yellow,
            _ => Color::White,
        }
    }
}

