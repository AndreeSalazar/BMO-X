//! USB HID Usage Page 0x07 — keycodes universales (independientes de layout).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum Key {
    None = 0x00,
    // Letras
    A = 0x04, B = 0x05, C = 0x06, D = 0x07, E = 0x08, F = 0x09,
    G = 0x0A, H = 0x0B, I = 0x0C, J = 0x0D, K = 0x0E, L = 0x0F,
    M = 0x10, N = 0x11, O = 0x12, P = 0x13, Q = 0x14, R = 0x15,
    S = 0x16, T = 0x17, U = 0x18, V = 0x19, W = 0x1A, X = 0x1B,
    Y = 0x1C, Z = 0x1D,
    // Números fila superior
    N1 = 0x1E, N2 = 0x1F, N3 = 0x20, N4 = 0x21, N5 = 0x22,
    N6 = 0x23, N7 = 0x24, N8 = 0x25, N9 = 0x26, N0 = 0x27,
    // Control / edición
    Enter = 0x28, Escape = 0x29, Backspace = 0x2A, Tab = 0x2B, Space = 0x2C,
    Minus = 0x2D, Equals = 0x2E, LeftBracket = 0x2F, RightBracket = 0x30,
    Backslash = 0x31, Semicolon = 0x33, Quote = 0x34, Grave = 0x35,
    Comma = 0x36, Period = 0x37, Slash = 0x38, CapsLock = 0x39,
    // F1..F12
    F1 = 0x3A, F2 = 0x3B, F3 = 0x3C, F4 = 0x3D, F5 = 0x3E, F6 = 0x3F,
    F7 = 0x40, F8 = 0x41, F9 = 0x42, F10 = 0x43, F11 = 0x44, F12 = 0x45,
    // Flechas y navegación
    PrintScreen = 0x46, ScrollLock = 0x47, Pause = 0x48,
    Insert = 0x49, Home = 0x4A, PageUp = 0x4B, Delete = 0x4C,
    End = 0x4D, PageDown = 0x4E,
    Right = 0x4F, Left = 0x50, Down = 0x51, Up = 0x52,
    // Keypad
    NumLock = 0x53, KpSlash = 0x54, KpStar = 0x55, KpMinus = 0x56,
    KpPlus = 0x57, KpEnter = 0x58,
    Kp1 = 0x59, Kp2 = 0x5A, Kp3 = 0x5B, Kp4 = 0x5C, Kp5 = 0x5D,
    Kp6 = 0x5E, Kp7 = 0x5F, Kp8 = 0x60, Kp9 = 0x61, Kp0 = 0x62,
}

impl Key {
    #[inline(always)]
    pub const fn raw(self) -> u8 { self as u8 }

    #[inline(always)]
    pub const fn is_letter(self) -> bool {
        let v = self as u8;
        v >= 0x04 && v <= 0x1D
    }

    #[inline(always)]
    pub const fn is_function(self) -> bool {
        let v = self as u8;
        v >= 0x3A && v <= 0x45
    }
}
