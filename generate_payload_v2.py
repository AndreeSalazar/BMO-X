class PB:
    def __init__(self): self.e=[]; self.l=[]
    def w32(s,r,v,d=""):
        s.e.append(struct.pack("<BII I",OP_WRITE32,r,4,v))
        s.l.append(f"W32 0x{r:06X}<-0x{v:08X} {d}")
    def r32(s,r,d=""):
        s.e.append(struct.pack("<BII",OP_READ32,r,0))
        s.l.append(f"R32 0x{r:06X} {d}")
    def p32(s,r,m,x,d=""):
        s.e.append(struct.pack("<BII",OP_POLL32,r,8)+struct.pack("<II",m,x))
        s.l.append(f"P32 0x{r:06X}&{m:X}=={x:X} {d}")
    def wctx(s,r,slot,d=""):
        s.e.append(struct.pack("<BII I",OP_WRITE_CONTEXT,r,4,slot))
        s.l.append(f"CTX [{slot}]->0x{r:06X} {d}")
    def falcon_dma(s, engine_base, dma_cmd, data, d=""):
        """OP_FALCON_DMA: kernel copies data to phys mem, then DMA to falcon"""
        pad = data + b'\x00' * ((256 - len(data) % 256) % 256)  # pad to 256B
        payload = struct.pack("<II", engine_base, dma_cmd) + pad
        s.e.append(struct.pack("<BII", OP_FALCON_DMA, 0, len(payload)) + payload)
        target = "IMEM" if (dma_cmd & 0x10) else "DMEM"
        s.l.append(f"DMA {target} 0x{engine_base:06X} cmd=0x{dma_cmd:08X} {len(data):,}B {d}")
    def build(s):
        return struct.pack("<4sII",b'FOSB',6,len(s.e))+b''.join(s.e)

def main():
    img_path = os.path.join(FIRMWARE_DIR, "booter_load_ga102_embedded.bin")
    with open(img_path,'rb') as f: img = f.read()
    assert len(img) == 60416
    code = img[APP_CODE_OFFSET : APP_CODE_OFFSET + APP_CODE_SIZE]
    data = img[OS_DATA_OFFSET  : OS_DATA_OFFSET  + OS_DATA_SIZE]
    
    # Append RSA-3K signature to DMEM data
    HS_SIG_DMEM_ADDR = len(data)  # = 0x6200
    dmem_data = data + SIG_PROD
    
    S=SEC2_BASE; R=0x841000
    b=PB()

    # ═══ 1. PRIV + PMC ═══
    b.w32(0x12004C,1,"PRIV"); b.w32(0x122204,1,"RING")
    b.p32(0x122100,1,1,"RING")
    b.w32(0x200,0xFFFFFFFF,"PMC"); b.w32(0x600,0xFFFFFFFF,"DEV")

    # ═══ 2. SEC2 Reset cycle ═══
    b.w32(R+0x668,0,"BCR")
    b.w32(S+0x100,0x40,"SRESET assert")     # Assert SRESET
    b.w32(S+0x100,0x00,"SRESET deassert")   # De-assert: CPU stopped, DMA enabled
    b.w32(S+0x10C,0,"DMACTL=no_ctx")
    # FBIF: all contexts → COHERENT_SYSMEM + PHYSICAL
    for i in range(8):
        b.w32(0x840600 + i*4, 0x05, f"FBIF[{i}]")

    # ═══ 3. DMA code into IMEM (secure) ═══
    b.falcon_dma(S, DMA_CMD_IMEM, code, "booter_load code")
    
    # ═══ 4. DMA data+sig into DMEM ═══
    b.falcon_dma(S, DMA_CMD_DMEM, dmem_data, "os_data+sig")

    # ═══ 5. BROM PKC auth ═══
    b.w32(R+0x180, 1, "MOD_SEL=RSA3K")
    b.w32(R+0x198, 0, "UCODE_ID")
    b.w32(R+0x19C, 0, "ENGIDMASK")
    b.w32(R+0x210, HS_SIG_DMEM_ADDR, f"PARAADDR=0x{HS_SIG_DMEM_ADDR:X}")

    # ═══ 6. BOOTVEC + MAILBOX + START ═══
    b.w32(S+0x104, BOOTVEC, "BVEC=0x100")
    b.wctx(S+0x040, 0, "MBOX0=wpr_lo")
    b.wctx(S+0x044, 1, "MBOX1=wpr_hi")
    b.w32(S+0x100, 0x02, "START!")

    # ═══ 7. Wait + Results ═══
    b.p32(S+0x008,0x10,0x10,"HALT")
    b.r32(S+0x100,"CPUCTL")
    b.r32(S+0x040,"MBOX0")
    b.r32(S+0x044,"MBOX1")
    b.r32(S+0x01C,"EXCI")
    b.r32(S+0x030,"TRACEPC")

    # ═══ 8. GSP ═══
    b.r32(0x110100, "GSP_CPU")
    b.r32(0x110040, "GSP_MB0")

    d=b.build()
    with open(OUTPUT_FILE,'wb') as f: f.write(d)
    
    print(f"v6.5 DMA — {len(b.e)} entries, {len(d):,}B")
    print(f"  CODE={len(code):,}B (DMA->IMEM, SEC=1)")
    print(f"  DMEM={len(dmem_data):,}B (os_data={len(data):,}B + sig={len(SIG_PROD)}B)")
    print(f"  PARAADDR[0] = 0x{HS_SIG_DMEM_ADDR:04X}")
    print(f"  DMA_CMD_IMEM = 0x{DMA_CMD_IMEM:08X}")
    print(f"  DMA_CMD_DMEM = 0x{DMA_CMD_DMEM:08X}")
    for i,l in enumerate(b.l,1): print(f"  [{i:02d}] {l}")

if __name__=="__main__": main()
